// В этом файле изучим работу union с нетривиальными членами

#include <iostream>
#include <vector>
#include <string>
#include <new>
// До С++11 в union можно было помещать POD-типы.
// Если тип пользовательский, например пользовательский
// класс со своими конструкторами, то его нельзя была добавлять.
// В С++11 эти ограничения были сняты.

// Вообще суть union в том что в одной области памяти
// могут хранится различные типы.
// Чтобы хранить пользовательские классы, придется
// учитывать несколько моментов.
// Во-первых использовать placement new чтобы конструировать
// объект в уже выделенной памяти union. По сути используется
// заново выделение памяти в куче, а используется область
// памяти которую union уже создал.
// Во-вторых вручную вызывать деструктор. Потому что фактически
// деструктор не будет вызван автоматически так как объект
// будет находится в памяти постоянно, а при перезаписывании
// в ту же область памяти, надо его очистить иначе будут
// некорректные данные.

// Обычно все это используют с enum чтобы были флаги,
// это делается чтобы знать какой тип сейчас находится в памяти
// и для него какой деструктор вызвать

struct TaggedUnion
{
    enum Type { INT, STRING, VECTOR } tag; // Флаги типов

    union
    {
        int i;
        std::string s;
        std::vector<int> v;
    }; // Анонимный union

    // Конструктор по умолчанию
    TaggedUnion() : tag(INT), i(0) {}

    //  Деструктор должен быть написан вручную!
    ~TaggedUnion()
    {
        destroy();
    }

    // Вспомогательный метод для вызова деструктора активного элемента
    void destroy()
    { // Через флаги узнаем какой тип сейчас занимает память
        if (tag == STRING)
            s.~basic_string(); // Явный вызов деструктора std::string
       else if (tag == VECTOR)
            v.~vector();       // Явный вызов деструктора std::vector
        // Для int (POD-тип) ничего вызывать не нужно
    }

    // Метод установки строки
    void setString(const std::string& str)
    {
        destroy();
        tag = STRING;
        new (&s) std::string(str); // Placement new: конструируем std::string в памяти union
    }

    // Метод установки вектора
    void setVector(const std::vector<int>& vec)
    {
        destroy();
        tag = VECTOR;
        new (&v) std::vector<int>(vec); // Placement new
    }
};

int main()
{
    TaggedUnion obj;

    obj.setString("Hello, Generalized Unions in C++11!");
    std::cout << "String: " << obj.s << '\n';

    obj.setVector({1, 2, 3, 4, 5});
    std::cout << "Vector size: " << obj.v.size() << '\n';

    // При выходе из main автоматически вызовется ~TaggedUnion(),
    // который корректно уничтожит std::vector без утечек памяти.
    return 0;
}
