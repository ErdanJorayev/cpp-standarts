// В этом файле изучим UTF-8 символьные литералы в С++17

#include <iostream>

int main()
{
    // Добавлены в С++11:
    char16_t c16 = u'Я';   // UTF-16 (2 байта) — для кириллицы/базовых символов
    char32_t c32 = U'😀';  // UTF-32 (4 байта) — для эмодзи и любых Юникод-символов

    // В С++17 добавили u8 для одиночных символов:
    char c8 = u8'A';       // UTF-8 (1 байт) — тип `char` (в C++20 станет `char8_t`)

    // Важное ограничение: u8'...' принимает только 1-байтовые символы (ASCII)
    // char invalid = u8'Я'; // Ошибка компиляции! 'Я' в UTF-8 занимает 2 байта

    return 0;
}
