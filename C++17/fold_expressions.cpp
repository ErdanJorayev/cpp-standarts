// В этом файле изучим Fold Expressions / Выражения свёртки (C++17)

#include <iostream>
#include <string>

// ============================================================================
// КАК БЫЛО ДО C++17 (C++11/14):
// Чтобы обработать пакет вариативных шаблонов (Args...), приходилось писать
// рекурсивные функции/классы и остановочные базовые случаи.
// Компилятор создавал кучу промежуточных функций и классов-матрешек в памяти!
// ============================================================================

// Остановочная функция C++11
template <typename T>
T sum_old(T val) 
{
    return val;
}

// Рекурсивный шаблон C++11 (плодил инстанции функций для каждого шага)
template <typename T, typename... Args>
T sum_old(T head, Args... tail) 
{
    return head + sum_old(tail...);
}


// ============================================================================
// КАК СТАЛО В C++17 (Fold Expressions):
// Промежуточные функции и классы-помощники БОЛЬШЕ НЕ СОЗДАЮТСЯ.
// Компилятор сразу разворачивает выражение в монолитную строчку кода!
// ============================================================================

// 1. Unary Left Fold (Односторонняя левая свёртка)
// Раскрывается в: ((a + b) + c)
template <typename... Args>
auto sum_new(Args... args) 
{
    return (... + args); // Запомни: скобки вокруг свёртки ОБЯЗАТЕЛЬНЫ!
}

// 2. Binary Left Fold (Двумерная свёртка с начальным значением)
// Нужна, чтобы обработать случай, когда передан ПУСТОЙ пакет аргументов.
// Раскрывается в: (((0 + a) + b) + c)
template <typename... Args>
auto safe_sum(Args... args) 
{
    return (0 + ... + args); // 0 — начальное значение (init)
}

// 3. Печать всех аргументов через оператор "запятая"
// Раскрывается в: ((std::cout << arg1 << ' '), (std::cout << arg2 << ' '), ...)
template <typename... Args>
void print_all(const Args&... args) 
{
    ((std::cout << args << ' '), ...);
    std::cout << '\n';
}

// 4. Использование свёртки внутри методов класса (без промежуточных предков)
template <typename... Types>
class PacketHandler {
public:
    void process(const Types&... args) 
    {
        std::cout << "Packet content: ";
        print_all(args...);
    }
};

int main() 
{
    // Вызов свёртки суммирования
    std::cout << "Sum: " << sum_new(10, 20, 30) << '\n'; // 60

    // Безопасная сумма с пустым набором элементов
    std::cout << "Empty sum: " << safe_sum() << '\n'; // 0

    // Печать разнородных типов за один вызов
    print_all("C++17", "Fold Expressions", 42, 3.14);

    // Работа внутри класса без рекурсивного наследования
    PacketHandler<int, std::string, double> handler;
    handler.process(1, "Test", 9.99);

    return 0;
}